"""ชนิดคอลัมน์ที่ต้องให้ผลเหมือนกันทุกยี่ห้อ (Phase 5 — ดู ADR 0026)

**`DATETIME` ของ MySQL/MariaDB ตัดเศษวินาทีทิ้งเงียบ ๆ** ถ้าไม่ระบุความละเอียด
ค่าที่ python เขียนลงไปเป็น `datetime.now(UTC)` ซึ่งมี microsecond เต็ม แต่สิ่งที่
อ่านกลับมาได้จะถูกปัดเป็นวินาที **โดยไม่มี warning และไม่มี error** — SQLite เก็บ
เป็นข้อความจึงไม่เคยเจอปัญหานี้ ผลคือบั๊กที่โผล่เฉพาะตอนย้ายยี่ห้อ:

* งานสองชิ้นที่สร้างห่างกัน 3 มิลลิวินาทีจะมี `created_at` เท่ากันเป๊ะ แล้ว
  `order_by(created_at.desc())` จะสลับลำดับกันเองแบบสุ่มตามที่ engine คืนมา
* เทสต์ที่เทียบเวลาที่เขียนไปกับเวลาที่อ่านกลับมาจะแดงแบบอธิบายไม่ถูก
* ค่าที่ถูกใช้คำนวณ hash ก่อนเขียน จะไม่ตรงกับค่าที่อ่านกลับมาคำนวณใหม่
  (`app/audit.py` แก้ด้วยการตัดเศษวินาทีทิ้งตั้งแต่ต้นทาง — ดูหมายเหตุข้างล่าง)

`UTCDateTime` จึงประกาศ variant ให้ MySQL/MariaDB เป็น `DATETIME(6)` ส่วนยี่ห้อ
อื่นได้ `DATETIME` ตามเดิม **DDL ของ SQLite ไม่เปลี่ยนเลย** ฐานข้อมูลที่มีอยู่แล้ว
จึงไม่ต้องทำอะไร (พิสูจน์ด้วยการเทียบ schema ตอน P5-03)

**ทุกคอลัมน์เวลาของ core ต้องใช้ตัวนี้ ไม่ใช่ `DateTime` เปล่า** —
`tests/test_dialect_parity.py` บังคับไว้ เพราะข้อผิดพลาดแบบนี้ไม่มีอะไรฟ้อง
จนกว่าจะมีคนย้ายไปยี่ห้ออื่นแล้วเจอข้อมูลที่ปัดไปแล้ว ซึ่งย้อนกลับไม่ได้

**หมายเหตุเรื่อง audit:** `tdl_audit.created_at` ยังตัดเศษวินาทีทิ้งเหมือนเดิม
ถึงจะมี `DATETIME(6)` แล้วก็ตาม — ไม่ใช่เพราะลืม แต่เพราะค่าที่ถูก hash ไปแล้ว
เปลี่ยนความละเอียดไม่ได้ สายที่มีอยู่จะ verify ไม่ผ่านทันที (ดู ADR 0015)
"""

from sqlalchemy import DateTime
from sqlalchemy.dialects import mysql

# ความละเอียดระดับ microsecond เท่าที่ `datetime` ของ python เก็บได้ (6 หลัก)
FRACTIONAL_SECONDS = 6

# import ตัว dialect ไม่ต้องมี driver ของยี่ห้อนั้นติดตั้งอยู่ — เป็นโค้ด python
# ล้วน ๆ ที่มากับ SQLAlchemy ซึ่งเป็น dependency ของ core อยู่แล้ว (สำคัญกับ
# job `bare` ที่ไม่ติดตั้งไลบรารีของ plugin ตัวไหนเลย)
UTCDateTime = DateTime().with_variant(mysql.DATETIME(fsp=FRACTIONAL_SECONDS), "mysql", "mariadb")
