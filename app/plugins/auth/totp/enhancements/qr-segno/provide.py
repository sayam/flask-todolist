"""วาด QR ของข้อความที่ส่งมา ด้วยไลบรารี segno

ส่วนเสริมตัวนี้ **ไม่รู้จัก TOTP ไม่รู้จักผู้ใช้ และไม่แตะฐานข้อมูล** — รับข้อความ
คืนรูป เท่านั้น ความลับที่อยู่ในข้อความนั้นเป็นเรื่องของ plugin แม่ซึ่งเป็นเจ้าของ
ข้อมูล (ADR 0025 ห้ามส่วนเสริมมี `models.py` ด้วยเหตุผลเดียวกัน) ขอบเขตแค่นี้
คือสิ่งที่ทำให้ตัวมันถูกถอดออกหรือถูกแทนด้วยไลบรารีเจ้าอื่นได้โดยไม่ต้องย้ายข้อมูล

ถอดไดเรกทอรีนี้ทิ้ง = ไม่มี QR ให้สแกน แต่การลงทะเบียนยังทำได้ครบด้วยการคัดลอก
ความลับไปวางในแอป ซึ่งเป็นทางที่แอป authenticator ทุกตัวรองรับอยู่แล้ว
"""

import io

# import ระดับบนสุดโดยตั้งใจ: ไลบรารีไม่ครบ = `ImportError` = registry ปิดส่วนเสริม
# นี้ให้เอง (ADR 0025) ไม่ต้องมี try/except ในนี้ให้เป็นเส้นทางสำรองอีกเส้น
import segno

MIMETYPE = "image/svg+xml"


def render(text: str) -> tuple[str, bytes]:
    """คืน `(mimetype, body)` ของ QR ที่เข้ารหัสข้อความนั้น

    **SVG ไม่ใช่ PNG โดยตั้งใจ** เป็นข้อความล้วน ไม่ต้องพึ่งไลบรารีวาดภาพเพิ่ม
    (segno ไม่มี dependency ต่อ) และคมทุกความละเอียดหน้าจอ

    **สีฝังมาในรูป ไม่ได้มาจากธีม** ตัวสแกนต้องการโมดูลเข้มบนพื้นอ่อนเสมอ
    ส่วนค่าเริ่มต้นของ segno คือพื้นโปร่งใส ซึ่งบนธีมโหมดมืดจะกลายเป็น
    สี่เหลี่ยมดำบนพื้นดำ = สแกนไม่ได้ นี่จึงเป็นข้อกำหนดของตัวสแกน ไม่ใช่เรื่องของ CSS
    """
    buffer = io.BytesIO()
    segno.make(text, error="m").save(
        buffer,
        kind="svg",
        scale=5,
        border=2,
        dark="#000000",
        light="#ffffff",
    )
    return MIMETYPE, buffer.getvalue()
