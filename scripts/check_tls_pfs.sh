#!/usr/bin/env bash
# ยืนยันว่าขา TLS ให้ perfect forward secrecy จริง — ไม่ใช่เชื่อว่าให้
#
# **TLS 1.3 มี PFS เสมอโดยนิยาม แต่ TLS 1.2 ไม่ใช่** ถ้าไม่จำกัดชุดรหัสลับไว้
# มันต่อรองไปใช้ชุดที่แลกกุญแจด้วย RSA ได้ ซึ่งแปลว่าใครที่เก็บทราฟฟิกไว้วันนี้
# แล้ววันหนึ่งได้กุญแจส่วนตัวของเซิร์ฟเวอร์ไป จะถอดรหัสย้อนหลังได้ทั้งหมด
#
# **`openssl s_client` ตอบเหมือนกันไม่ว่าเซิร์ฟเวอร์ปฏิเสธ หรือไม่มีใครฟังพอร์ต**
# (กับดักที่ docs/SECURITY-CADENCE.md บันทึกไว้) — ที่นี่จึงยิง "ตัวคุม" ที่ต้อง
# สำเร็จก่อนเสมอ การปฏิเสธถึงจะแปลว่าปฏิเสธจริง ไม่ใช่แปลว่ายิงผิดที่
#
# ใช้: scripts/check_tls_pfs.sh [host:port]   (ค่าเริ่มต้น 127.0.0.1:8443)
set -euo pipefail

target="${1:-127.0.0.1:8443}"
status=0

# ชุดที่แลกกุญแจด้วย RSA ล้วน — ไม่มี PFS · ถ้าเซิร์ฟเวอร์ยอมรับแม้ชุดเดียว
# แปลว่ามีทางลงไปอยู่ในสถานะที่ไม่มี PFS
NO_PFS='AES128-GCM-SHA256:AES256-GCM-SHA384:AES128-SHA256:AES256-SHA256:AES128-SHA:AES256-SHA:DES-CBC3-SHA'

negotiated() {
    # คืนชื่อชุดรหัสลับที่ตกลงกันได้ หรือว่างถ้าจับมือไม่สำเร็จ
    #
    # **อ่านจาก exit code กับบรรทัดสรุป `New, ...` ไม่ใช่จากบรรทัด `Cipher :`
    # ในบล็อก session** — บรรทัดนั้นพิมพ์ `0000` ตอนจับมือไม่สำเร็จ ซึ่ง *ไม่ว่าง*
    # ด่านที่อ่านมันจึงแปล "ถูกปฏิเสธ" เป็น "ยอมรับชุดชื่อ 0000"
    # (เขียนผิดแบบนี้มาแล้วตอนวัดครั้งแรก แล้วมันรายงานว่าการแก้ทำ TLS 1.3 พัง
    # ทั้งที่ TLS 1.3 ทำงานปกติ — ด่านที่วัดผิดตัวสร้างสัญญาณเตือนลวงได้ด้วย
    # ไม่ใช่แค่เงียบตอนควรดัง)
    local out
    if ! out=$(openssl s_client -connect "$target" -servername localhost "$@" </dev/null 2>/dev/null); then
        return 0   # จับมือไม่สำเร็จ = ไม่มีชุดที่ตกลงได้ ซึ่งบางกรณีคือผลที่ต้องการ
    fi
    printf '%s' "$out" | sed -n 's/^New, TLSv[0-9.]*, Cipher is //p' | head -1 | tr -d '[:space:]'
}

echo "== ตัวคุม: TLS 1.2 ด้วยชุดปกติ ต้องจับมือได้"
control=$(negotiated -tls1_2 || true)
if [ -z "$control" ] || [ "$control" = "(NONE)" ]; then
    echo "   จับมือไม่ได้เลยที่ $target — ยังไม่ได้ทดสอบอะไร (เซิร์ฟเวอร์ไม่ขึ้น?)" >&2
    exit 2
fi
echo "   ได้ $control"

echo "== ชุดที่ตกลงเองต้องเป็น ECDHE (มี PFS)"
case "$control" in
    ECDHE-*|TLS_*) echo "   ผ่าน — $control" ;;
    *) echo "   **ไม่ผ่าน** — ตกลงได้ $control ซึ่งแลกกุญแจโดยไม่มี PFS" >&2; status=1 ;;
esac

echo "== บังคับใช้ชุดที่ไม่มี PFS ต้องถูกปฏิเสธ"
forced=$(negotiated -tls1_2 -cipher "$NO_PFS" || true)
if [ -z "$forced" ] || [ "$forced" = "(NONE)" ]; then
    echo "   ผ่าน — เซิร์ฟเวอร์ปฏิเสธ (และตัวคุมข้างบนพิสูจน์แล้วว่ามีคนฟังอยู่จริง)"
else
    echo "   **ไม่ผ่าน** — เซิร์ฟเวอร์ยอมรับ $forced ซึ่งไม่มี PFS" >&2
    status=1
fi

echo "== TLS 1.3 ต้องยังใช้ได้ (มี PFS เสมอโดยนิยาม)"
tls13=$(negotiated -tls1_3 || true)
if [ -n "$tls13" ] && [ "$tls13" != "(NONE)" ]; then
    echo "   ผ่าน — $tls13"
else
    echo "   **ไม่ผ่าน** — TLS 1.3 จับมือไม่ได้ การจำกัดชุดรหัสลับแรงเกินไปหรือเปล่า" >&2
    status=1
fi

[ "$status" -eq 0 ] && echo "ผ่านครบ — ขา TLS นี้ให้ PFS ทุกทางที่เข้าถึงได้"
exit "$status"
